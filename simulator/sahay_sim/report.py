"""Aggregate shards into tables (markdown + CSV) and charts (PNG)."""
import csv
import json
import math
from pathlib import Path

import numpy as np

from .learner import TYPE_NAMES
from .run import CONDITIONS

LABEL = {"full": "Full Sahay planner", "fixed_linear": "Fixed linear roadmap", "topic_only": "Topic-only (no misconceptions)",
         "no_forgetting": "No forgetting curve", "random_order": "Random order", "no_replan": "No re-planning",
         "no_diagnostic": "No diagnostic"}


def load(outdir):
    rows = []
    for p in sorted((Path(outdir) / "shards").glob("*.json")):
        rows += json.loads(p.read_text(encoding="utf-8"))
    return rows


def ci(xs):
    xs = [x for x in xs if x is not None]
    if not xs:
        return None, None, 0
    a = np.array(xs, float)
    m = a.mean()
    h = 1.96 * a.std(ddof=1) / math.sqrt(len(a)) if len(a) > 1 else 0.0
    return m, h, len(a)


def fmt(xs, pct=False, d=2):
    m, h, n = ci(xs)
    if m is None:
        return "n/a"
    if pct:
        return "%.1f%% ± %.1f" % (100 * m, 100 * h)
    return ("%." + str(d) + "f ± %." + str(d) + "f") % (m, h)


def make_report(outdir, per_type, docs_out):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    rows = load(outdir)
    main = [r for r in rows if not r["cond"].startswith("gap_")]
    gap = [r for r in rows if r["cond"].startswith("gap_")]
    docs_out = Path(docs_out)
    docs_out.mkdir(parents=True, exist_ok=True)
    by = {}
    for r in main:
        by.setdefault(r["cond"], []).append(r)
    md = ["# Simulator results", "",
          "Generated by `python simulator/run_all.py`. %d learners per type x 8 types = %d learners per condition; "
          "same learners and attendance in every condition (paired). Values are mean ± 95%% CI.  " % (per_type, per_type * 8),
          "**These are results inside a simulated-learner model whose parameters are assumptions (see `simulator/sahay_sim/learner.py`). "
          "They compare planners with each other; they are not evidence about real students.**", ""]
    # ---- table 1 ----
    md += ["## 1. Planners compared (all learner types pooled, 12-week horizon, 6 h/week)", "",
           "| Condition | Hours to target* | Reached target | True mastery at end | Retention day 30 | Misconceptions resolved | Prerequisite violations / learner | Mastery-estimate AUC | Plan stability (items moved) |",
           "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    csvrows = []
    for c in CONDITIONS:
        rs = by.get(c, [])
        if not rs:
            continue
        row = [LABEL[c], fmt([r["hours"] for r in rs], d=1), fmt([1.0 if r["reached"] else 0.0 for r in rs], pct=True),
               fmt([r["mean_k_end"] for r in rs]), fmt([r["retention30"] for r in rs]),
               fmt([r["mis_resolved"] for r in rs], pct=True), fmt([r["prereq_violations"] for r in rs]),
               fmt([r["auc"] for r in rs]), fmt([r["stability"] for r in rs])]
        md.append("| " + " | ".join(row) + " |")
        csvrows.append([c] + row[1:])
    md += ["", "\\* Study hours (plus diagnostic time) until mean true mastery over the goal skills reaches 0.8; learners who never get there are "
           "counted at the hours they studied by the end of the horizon (censored), so compare this column together with 'Reached target'.", ""]
    # ---- paired vs fixed ----
    full = {(r["domain"], r["type"], r["idx"]): r for r in by.get("full", [])}
    fix = {(r["domain"], r["type"], r["idx"]): r for r in by.get("fixed_linear", [])}
    keys = sorted(set(full) & set(fix))
    if keys:
        dh = [full[k]["hours"] - fix[k]["hours"] for k in keys]
        dk = [full[k]["mean_k_end"] - fix[k]["mean_k_end"] for k in keys]
        dr = [full[k]["retention30"] - fix[k]["retention30"] for k in keys]
        mf, mx = np.mean([full[k]["hours"] for k in keys]), np.mean([fix[k]["hours"] for k in keys])
        md += ["## 2. Full planner vs fixed linear roadmap (paired differences)", "",
               "| Metric | Full - Fixed (mean ± 95% CI) |", "| --- | --- |",
               "| Study hours | %s (%.1f%% change in mean hours) |" % (fmt(dh, d=1), 100 * (mf - mx) / mx),
               "| True mastery at end | %s |" % fmt(dk), "| Retention at day 30 | %s |" % fmt(dr), "",
               "PRD target: at least 20%% fewer study hours to reach target mastery. In this simulation the change in mean hours is %.1f%%, so the target is **%s**; "
               "most learners do not reach 0.8 within the horizon, so hours are censored and the planner's effect shows up mainly as higher mastery for similar hours." % (
                   100 * (mf - mx) / mx, "met" if (mf - mx) / mx <= -0.2 else "NOT met"), ""]
    # ---- per type ----
    md += ["## 3. Per learner type: full planner vs fixed roadmap (true mastery at end of horizon)", "",
           "| Learner type | Full | Fixed | Full reached target | Fixed reached target |", "| --- | --- | --- | --- | --- |"]
    for t in TYPE_NAMES:
        a = [r for r in by.get("full", []) if r["type"] == t]
        b = [r for r in by.get("fixed_linear", []) if r["type"] == t]
        if a and b:
            md.append("| %s | %s | %s | %s | %s |" % (t, fmt([r["mean_k_end"] for r in a]), fmt([r["mean_k_end"] for r in b]),
                                                     fmt([1.0 if r["reached"] else 0.0 for r in a], pct=True), fmt([1.0 if r["reached"] else 0.0 for r in b], pct=True)))
    md.append("")
    # ---- ablations ----
    md += ["## 4. Ablations (remove one feature at a time from the full planner; difference vs full, paired)", "",
           "| Removed feature | Condition | Δ true mastery at end | Δ retention day 30 | Δ misconceptions resolved |", "| --- | --- | --- | --- | --- |"]
    for c, what in (("topic_only", "misconception engine"), ("no_forgetting", "forgetting curve and revision"),
                    ("no_replan", "re-planning"), ("no_diagnostic", "diagnostic")):
        ab = {(r["domain"], r["type"], r["idx"]): r for r in by.get(c, [])}
        ks = sorted(set(full) & set(ab))
        if ks:
            md.append("| %s | %s | %s | %s | %s |" % (what, LABEL[c], fmt([ab[k]["mean_k_end"] - full[k]["mean_k_end"] for k in ks], d=3),
                                                     fmt([ab[k]["retention30"] - full[k]["retention30"] for k in ks], d=3),
                                                     fmt([(ab[k]["mis_resolved"] - full[k]["mis_resolved"]) if (ab[k]["mis_resolved"] is not None and full[k]["mis_resolved"] is not None) else None for k in ks], d=3)))
    md += ["", "Negative values mean removing the feature made things worse. The hint ladder and confidence calibration (I1) do not change a "
           "simulated learner's knowledge, so they are not ablated here; their value needs the human pilot.", ""]
    # ---- recovery ----
    gm = {}
    for r in gap:
        gm.setdefault(r["cond"], []).append(r)
    if gm:
        md += ["## 5. Recovery quality: 7-day gap on day 15 of a 6-week plan (average learners)", "",
               "| Mode | True mastery at deadline | Retention day 30 |", "| --- | --- | --- |"]
        names = {"gap_nogap": "No gap (reference)", "gap_replan": "Gap, ordinary re-plan", "gap_recover": "Gap, Recover mode (knapsack)"}
        for k in ("gap_nogap", "gap_replan", "gap_recover"):
            if k in gm:
                md.append("| %s | %s | %s |" % (names[k], fmt([r["mean_k_end"] for r in gm[k]]), fmt([r["retention30"] for r in gm[k]])))
        a = {(r["domain"], r["idx"]): r for r in gm.get("gap_replan", [])}
        b = {(r["domain"], r["idx"]): r for r in gm.get("gap_recover", [])}
        ks = sorted(set(a) & set(b))
        if ks:
            md += ["", "Recover minus ordinary re-plan (paired): %s true mastery." % fmt([b[k]["mean_k_end"] - a[k]["mean_k_end"] for k in ks], d=3)]
        md.append("")
    (docs_out / "results.md").write_text("\n".join(md), encoding="utf-8")
    with open(docs_out / "summary.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["condition", "hours", "reached", "mastery_end", "retention30", "mis_resolved", "prereq_violations", "auc", "stability"])
        w.writerows(csvrows)
    # ---- charts ----
    fig, ax = plt.subplots(figsize=(8, 4))
    conds = [c for c in CONDITIONS if c in by]
    ms = [ci([r["mean_k_end"] for r in by[c]]) for c in conds]
    ax.barh([LABEL[c] for c in conds][::-1], [m[0] for m in ms][::-1], xerr=[m[1] for m in ms][::-1], color="#2f6fb0")
    ax.set_xlabel("Mean true mastery of goal skills at end of 12 weeks")
    ax.set_xlim(0, 1)
    ax.set_title("Planner comparison (simulated learners, 95% CI)")
    fig.tight_layout(); fig.savefig(docs_out / "mastery_by_planner.png", dpi=150); plt.close(fig)
    fig, ax = plt.subplots(figsize=(8, 4))
    x = np.arange(len(TYPE_NAMES))
    for off, c, col in ((-0.2, "full", "#2f6fb0"), (0.2, "fixed_linear", "#b0622f")):
        vals = [ci([r["mean_k_end"] for r in by.get(c, []) if r["type"] == t]) for t in TYPE_NAMES]
        ax.bar(x + off, [v[0] or 0 for v in vals], 0.4, yerr=[v[1] or 0 for v in vals], label=LABEL[c], color=col)
    ax.set_xticks(x); ax.set_xticklabels(TYPE_NAMES, rotation=30, ha="right"); ax.set_ylabel("True mastery at end"); ax.legend(); ax.set_ylim(0, 1)
    ax.set_title("Full planner vs fixed roadmap by learner type")
    fig.tight_layout(); fig.savefig(docs_out / "mastery_by_type.png", dpi=150); plt.close(fig)
    if gm:
        fig, ax = plt.subplots(figsize=(6, 4))
        ks = [k for k in ("gap_nogap", "gap_replan", "gap_recover") if k in gm]
        vals = [ci([r["mean_k_end"] for r in gm[k]]) for k in ks]
        ax.bar(["No gap", "Re-plan", "Recover"][:len(ks)], [v[0] for v in vals], yerr=[v[1] for v in vals], color=["#888", "#b0622f", "#2f6fb0"][:len(ks)])
        ax.set_ylabel("True mastery at deadline"); ax.set_ylim(0, 1); ax.set_title("7-day gap: ordinary re-plan vs Recover mode")
        fig.tight_layout(); fig.savefig(docs_out / "recovery.png", dpi=150); plt.close(fig)
    print("wrote", docs_out / "results.md")
